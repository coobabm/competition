        /// <summary>Keys are AppLibrary appTitle values, plus StartOrb and Wallpaper.</summary>
        public static Dictionary<string, Sprite> BuildAssets()
        {
            Directory.CreateDirectory(ArtDirectory);
            var drawings = new Dictionary<string, Action<Painter>>(StringComparer.Ordinal)
            {
                { "Calculator", Calculator }, { "Commander", Commander },
                { "Game Hub", GameHub }, { "Mail", Mail },
                { "Messaging", Messaging }, { "Music Player", MusicPlayer },
                { "Notepad", Notepad }, { "Photo Gallery", PhotoGallery },
                { "Reminder", Reminder }, { "Settings", Settings },
                { "Video Player", VideoPlayer }, { "Web Browser", WebBrowser },
                { "Widget Library", WidgetLibrary }, { "StartOrb", StartOrb }
            };
            var result = new Dictionary<string, Sprite>(StringComparer.Ordinal);
            foreach (KeyValuePair<string, Action<Painter>> entry in drawings)
            {
                var canvas = new Painter(128, 128);
                entry.Value(canvas);
                string path = entry.Key == "StartOrb" ? StartOrbPath : ArtDirectory + "/Aero-" + entry.Key.Replace(' ', '-') + ".png";
                result.Add(entry.Key, SaveSprite(path, canvas.Export(), 128, 128, true));
            }
            result.Add("Wallpaper", SaveSprite(WallpaperPath, BuildWallpaper(), 1920, 1080, false));
            File.WriteAllText(ArtDirectory + "/README-Original-Art.txt",
                "HongmengOS Aero 2010 original artwork\n\n" +
                "Generated by AeroIconBuilder from original geometric drawings and analytic gradients.\n" +
                "13 glossy 128x128 desktop icons, an original four-petal Start orb, and a 1920x1080 blue Aurora wallpaper.\n" +
                "No Microsoft logos, Windows wallpaper images, remote images, or Lucide derivatives are included.\n" +
                "Desktop icon dictionary keys match AppLibrary appTitle; additional keys: StartOrb, Wallpaper.\n" +
                "Bilinear, uncompressed, no mipmaps. Source scene and the Retro art collection are not modified.\n");
            AssetDatabase.ImportAsset(ArtDirectory + "/README-Original-Art.txt", ImportAssetOptions.ForceSynchronousImport);
            // Imported generated assets are already saved; do not save unrelated dirty assets.
            return result;
        }

        private static Sprite SaveSprite(string path, Color32[] pixels, int width, int height, bool alpha)
        {
            var texture = new Texture2D(width, height, TextureFormat.RGBA32, false, false);
            try
            {
                texture.SetPixels32(pixels); texture.Apply(false, false);
                File.WriteAllBytes(path, texture.EncodeToPNG());
            }
            finally { UnityEngine.Object.DestroyImmediate(texture); }
            AssetDatabase.ImportAsset(path, ImportAssetOptions.ForceSynchronousImport);
            var importer = AssetImporter.GetAtPath(path) as TextureImporter;
            if (importer == null) throw new InvalidOperationException("No texture importer for " + path);
            importer.textureType = TextureImporterType.Sprite;
            importer.spriteImportMode = SpriteImportMode.Single;
            importer.spritePixelsPerUnit = 128;
            importer.alphaSource = alpha ? TextureImporterAlphaSource.FromInput : TextureImporterAlphaSource.None;
            importer.alphaIsTransparency = alpha;
            importer.filterMode = FilterMode.Bilinear;
            importer.wrapMode = TextureWrapMode.Clamp;
            importer.mipmapEnabled = false;
            importer.isReadable = false;
            importer.npotScale = TextureImporterNPOTScale.None;
            importer.textureCompression = TextureImporterCompression.Uncompressed;
            importer.maxTextureSize = width > 128 ? 2048 : 128;
            importer.sRGBTexture = true;
            var settings = new TextureImporterSettings();
            importer.ReadTextureSettings(settings); settings.spriteMeshType = SpriteMeshType.FullRect;
            importer.SetTextureSettings(settings); importer.SaveAndReimport();
            var sprite = AssetDatabase.LoadAssetAtPath<Sprite>(path);
            if (sprite == null) throw new InvalidOperationException("Sprite import failed: " + path);
            return sprite;
        }

