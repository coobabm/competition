        private static Color32[] BuildWallpaper()
        {
            const int width=1920,height=1080;
            var pixels=new Color32[width*height];
            Color top=Hex(0x061E42),bottom=Hex(0x0769A8);
            for(int y=0;y<height;y++)for(int x=0;x<width;x++)
            {
                float u=(x+.5f)/width,v=(y+.5f)/height;
                Color color=Color.Lerp(top,bottom,Mathf.Pow(v,.80f));
                float atmosphere=Gaussian((u-.64f)/.60f,(v-.60f)/.68f);
                color+=new Color(.014f,.115f,.18f,0)*atmosphere;
                float horizon=Gaussian((u-.68f)/.43f,(v-.91f)/.29f);
                color+=new Color(.015f,.16f,.13f,0)*horizon;
                float violet=Gaussian((u-.98f)/.32f,(v-.17f)/.5f);
                color+=new Color(.023f,.012f,.048f,0)*violet;
                for(int ribbon=0;ribbon<4;ribbon++)
                {
                    float offset=ribbon*.055f;
                    float center=.96f-.44f*u+.13f*Mathf.Sin(u*5.1f-.5f)+offset;
                    float distance=v-center;
                    float broad=Mathf.Exp(-distance*distance/(.0025f+ribbon*.001f));
                    float thread=Mathf.Exp(-distance*distance/.0000036f);
                    float fade=Mathf.Sin(Mathf.Clamp01(u*.9f+.06f)*Mathf.PI)*(.13f-ribbon*.018f);
                    color+=new Color(.24f,.78f,.92f,0)*(broad*fade);
                    color+=new Color(.54f,.91f,1f,0)*(thread*(.075f-ribbon*.012f));
                }
                float sweepCenter=1.10f-.68f*u+.06f*Mathf.Sin(u*8);
                float sweepDistance=v-sweepCenter;
                color+=new Color(.06f,.24f,.32f,0)*Mathf.Exp(-sweepDistance*sweepDistance/.018f)*Mathf.SmoothStep(.15f,.85f,u)*.32f;
                float edge=Mathf.Pow(Mathf.Abs(u-.5f)*1.25f,2)+Mathf.Pow(Mathf.Abs(v-.5f)*.65f,2);
                color*=1-edge*.12f;color.a=1;
                pixels[(height-1-y)*width+x]=color;
            }
            return pixels;
        }

        private static float Gaussian(float x,float y){return Mathf.Exp(-(x*x+y*y)*2);}
        private static Color Hex(int rgb){return new Color(((rgb>>16)&255)/255f,((rgb>>8)&255)/255f,(rgb&255)/255f,1);}
        private static Color A(Color color,float alpha){color.a=alpha;return color;}

        /// <summary>Small antialiased SDF rasterizer. Coordinates start at top-left.</summary>
        private sealed class Painter
        {
            private readonly int width,height;
            private readonly Color[] data;
            public Painter(int width,int height){this.width=width;this.height=height;data=new Color[width*height];}
            public Color32[] Export(){var result=new Color32[data.Length];for(int i=0;i<data.Length;i++)result[i]=data[i];return result;}
            private void Blend(int x,int y,Color source,float coverage)
            {
                int index=(height-1-y)*width+x;Color destination=data[index];
                float alpha=Mathf.Clamp01(source.a*coverage),outAlpha=alpha+destination.a*(1-alpha);
                if(outAlpha<=0)return;
                data[index]=new Color((source.r*alpha+destination.r*destination.a*(1-alpha))/outAlpha,
                    (source.g*alpha+destination.g*destination.a*(1-alpha))/outAlpha,
                    (source.b*alpha+destination.b*destination.a*(1-alpha))/outAlpha,outAlpha);
            }
            private void Shape(Rect bounds,Func<float,float,float> distance,Func<float,float,Color> shade)
            {
                int x0=Mathf.Max(0,Mathf.FloorToInt(bounds.xMin-1)),x1=Mathf.Min(width-1,Mathf.CeilToInt(bounds.xMax+1));
                int y0=Mathf.Max(0,Mathf.FloorToInt(bounds.yMin-1)),y1=Mathf.Min(height-1,Mathf.CeilToInt(bounds.yMax+1));
                for(int y=y0;y<=y1;y++)for(int x=x0;x<=x1;x++)
                {
                    float xx=x+.5f,yy=y+.5f;float coverage=Mathf.Clamp01(.65f-distance(xx,yy));
                    if(coverage>0)Blend(x,y,shade(xx,yy),coverage);
                }
            }
            public void Round(float x,float y,float w,float h,float radius,Color top,Color bottom,Color? border=null,float stroke=0)
            {
                if(border.HasValue&&stroke>0)
                {
                    Round(x,y,w,h,radius,border.Value,border.Value);
                    x+=stroke;y+=stroke;w-=stroke*2;h-=stroke*2;radius=Mathf.Max(0,radius-stroke);
                }
                float xx=x,yy=y,ww=w,hh=h,rr=Mathf.Min(radius,Mathf.Min(w,h)*.5f);
                Shape(new Rect(xx,yy,ww,hh),(px,py)=>{
                    float qx=Mathf.Abs(px-(xx+ww*.5f))-(ww*.5f-rr),qy=Mathf.Abs(py-(yy+hh*.5f))-(hh*.5f-rr);
                    return Mathf.Sqrt(Mathf.Max(qx,0)*Mathf.Max(qx,0)+Mathf.Max(qy,0)*Mathf.Max(qy,0))+Mathf.Min(Mathf.Max(qx,qy),0)-rr;
                },(px,py)=>Color.Lerp(top,bottom,(py-yy)/hh));
            }
            public void Ellipse(float cx,float cy,float rx,float ry,Color top,Color bottom,Color? border=null,float stroke=0)
            {
                if(border.HasValue&&stroke>0){Ellipse(cx,cy,rx,ry,border.Value,border.Value);rx-=stroke;ry-=stroke;}
                float rxx=rx,ryy=ry;
                Shape(new Rect(cx-rxx,cy-ryy,rxx*2,ryy*2),(x,y)=>{
                    float dx=(x-cx)/rxx,dy=(y-cy)/ryy;return (Mathf.Sqrt(dx*dx+dy*dy)-1)*Mathf.Min(rxx,ryy);
                },(x,y)=>Color.Lerp(top,bottom,(y-cy+ryy)/(ryy*2)));
            }
            public void Line(float ax,float ay,float bx,float by,float thickness,Color color)
            {
                float radius=thickness*.5f,dx=bx-ax,dy=by-ay,length=dx*dx+dy*dy;
                Shape(new Rect(Mathf.Min(ax,bx)-radius,Mathf.Min(ay,by)-radius,Mathf.Abs(dx)+thickness,Mathf.Abs(dy)+thickness),(x,y)=>{
                    float t=length>0?Mathf.Clamp01(((x-ax)*dx+(y-ay)*dy)/length):0;
                    float xx=x-ax-dx*t,yy=y-ay-dy*t;return Mathf.Sqrt(xx*xx+yy*yy)-radius;
                },(x,y)=>color);
            }
            public void Poly(Color top,Color bottom,params float[] points)
            {
                if(points.Length<6||points.Length%2!=0)throw new ArgumentException("Polygon needs x/y pairs.");
                int count=points.Length/2;float minX=128,minY=128,maxX=0,maxY=0;
                for(int i=0;i<count;i++){minX=Mathf.Min(minX,points[i*2]);maxX=Mathf.Max(maxX,points[i*2]);minY=Mathf.Min(minY,points[i*2+1]);maxY=Mathf.Max(maxY,points[i*2+1]);}
                float y0=minY,span=Mathf.Max(1,maxY-minY);
                Shape(new Rect(minX,minY,maxX-minX,maxY-minY),(x,y)=>{
                    bool inside=false;float minimum=float.MaxValue;
                    for(int i=0,j=count-1;i<count;j=i++)
                    {
                        float ax=points[j*2],ay=points[j*2+1],bx=points[i*2],by=points[i*2+1],dx=bx-ax,dy=by-ay;
                        if((by>y)!=(ay>y)&&x<(ax-bx)*(y-by)/(ay-by)+bx)inside=!inside;
                        float length=dx*dx+dy*dy,t=length>0?Mathf.Clamp01(((x-ax)*dx+(y-ay)*dy)/length):0;
                        float xx=x-ax-dx*t,yy=y-ay-dy*t;minimum=Mathf.Min(minimum,xx*xx+yy*yy);
                    }
                    return Mathf.Sqrt(minimum)*(inside?-1:1);
                },(x,y)=>Color.Lerp(top,bottom,(y-y0)/span));
            }
            public void Arc(float cx,float cy,float rx,float ry,float start,float end,float thickness,Color color)
            {
                float previous=start*Mathf.Deg2Rad;
                for(float angle=start+2;angle<=end+1;angle+=2)
                {float next=Mathf.Min(angle,end)*Mathf.Deg2Rad;Line(cx+Mathf.Cos(previous)*rx,cy+Mathf.Sin(previous)*ry,cx+Mathf.Cos(next)*rx,cy+Mathf.Sin(next)*ry,thickness,color);previous=next;}
            }
            public void Shadow(float cx,float cy,float rx,float ry,float opacity)
            {
                int x0=Mathf.Max(0,(int)(cx-rx*1.4f)),x1=Mathf.Min(width-1,(int)(cx+rx*1.4f));
                int y0=Mathf.Max(0,(int)(cy-ry*2)),y1=Mathf.Min(height-1,(int)(cy+ry*2));
                for(int y=y0;y<=y1;y++)for(int x=x0;x<=x1;x++)
                {float dx=(x-cx)/rx,dy=(y-cy)/ry;float a=Mathf.Exp(-(dx*dx+dy*dy)*2)*opacity;Blend(x,y,new Color(.015f,.035f,.07f,a),1);}
            }
            public void Star(float cx,float cy,float outer,float inner,int tips,Color top,Color bottom)
            {
                var points=new float[tips*4];for(int i=0;i<tips*2;i++){float a=i*Mathf.PI/tips-Mathf.PI*.5f,r=i%2==0?outer:inner;points[i*2]=cx+Mathf.Cos(a)*r;points[i*2+1]=cy+Mathf.Sin(a)*r;}Poly(top,bottom,points);
            }
            public void Seven(float x,float y,int number,Color color)
            {
                int mask=number==4?0x66:number==2?0x5b:0x3f;
                float[,] bars={{2,0,9,0},{10,1,10,6},{10,8,10,13},{2,14,9,14},{1,8,1,13},{1,1,1,6},{2,7,9,7}};
                for(int i=0;i<7;i++)if((mask&(1<<i))!=0)Line(x+bars[i,0],y+bars[i,1],x+bars[i,2],y+bars[i,3],1.4f,color);
            }
        }
