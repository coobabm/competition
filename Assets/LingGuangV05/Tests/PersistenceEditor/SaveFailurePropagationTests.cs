using System;
using System.Collections.Generic;
using System.IO;
using System.Reflection;
using NUnit.Framework;
using UnityEngine;
using LingGuangV05.Core;
using LingGuangV05.Runtime;
using LingGuangV05.Runtime.Persistence;
using Object = UnityEngine.Object;

namespace LingGuangV05.Tests
{
    /// <summary>
    /// E1 (2026-10-19): latest-version save/exit integrity. Failure injection only through Saving callbacks and files
    /// inside freshly generated temp directories owned by this fixture. Never touches LocalLow, the registry or
    /// PlayerPrefs. Includes failure propagation and regression guards; execution is tracked separately in the report.
    /// </summary>
    public sealed class SaveFailurePropagationTests
    {
        const BindingFlags Flags = BindingFlags.Instance | BindingFlags.NonPublic | BindingFlags.Public;
        readonly List<string> owned = new List<string>();
        string directory;
        GameObject root;
        ChapterOneRuntime runtime;
        string previousVerification;
        Func<string, bool> previousLab;
        IDisposable locale;

        string NewTemp()
        {
            string path = Path.Combine(Path.GetTempPath(), "lingguang-e1-save-tests-" + Guid.NewGuid().ToString("N"));
            owned.Add(path);
            return path;
        }

        [SetUp] public void Setup()
        {
            // A leftover editor-wide QA root must not decide where this fixture writes.
            previousVerification = ChapterOneRuntime.VerificationSaveDirectory; ChapterOneRuntime.VerificationSaveDirectory = null;
            previousLab = ChapterOneRuntime.LabStateReadable; ChapterOneRuntime.LabStateReadable = null;
            locale = GameText.Bind(() => GameText.Chinese);
            directory = NewTemp();
            Assert.That(VerificationSavePaths.Root, Is.Null,
                "Run this fixture without --verification-save-dir; it owns a separate temporary directory per test.");
            Open();
            var profile = PrologueProfile.Read("嘴硬心软"); profile.name = "测试"; profile.self = "我"; profile.callMe = "你";
            Assert.That(runtime.CompletePrologue(profile), Is.True, runtime.SaveStatus);
        }

        [TearDown] public void Cleanup()
        {
            if (root != null) Object.DestroyImmediate(root);
            root = null;
            ChapterOneRuntime.VerificationSaveDirectory = previousVerification;
            ChapterOneRuntime.LabStateReadable = previousLab;
            locale?.Dispose(); locale = null;
            // Only the directories generated by NewTemp in this fixture.
            foreach (string path in owned) if (Directory.Exists(path)) Directory.Delete(path, true);
            owned.Clear();
        }

        void Open(string folder = null, Action<ChapterOneRuntime> beforeInitialize = null)
        {
            if (root != null) Object.DestroyImmediate(root);
            root = new GameObject("IsolatedE1SaveTest"); root.SetActive(false);
            runtime = root.AddComponent<ChapterOneRuntime>();
            runtime.useDiskSave = true;
            runtime.ClockOverride = () => 1000;
            runtime.SaveDirectoryOverride = folder ?? directory;
            beforeInitialize?.Invoke(runtime);
            runtime.EnsureInitialized();
        }

        string Primary => Path.Combine(directory, "chapter-one.sav");
        string Backup => Primary + ".bak";
        static byte[] Bytes(string path) => File.Exists(path) ? File.ReadAllBytes(path) : null;
        bool Dirty => (bool)typeof(ChapterOneRuntime).GetField("dirty", Flags).GetValue(runtime);
        GameState DiskState()
        {
            var loaded = new AtomicSaveStore(directory).Load();
            Assert.That(loaded.Success, Is.True, loaded.Message);
            return JsonUtility.FromJson<GameState>(loaded.Payload);
        }

        /// <summary>Same path as BankruptcyRestartTests: three days below zero, then the player agrees to sell.</summary>
        void GoBankrupt()
        {
            var sim = runtime.Sim;
            GameCalendar.Advance(sim.S, GameCalendar.DayIndex(new DateTime(2016, 6, 3)));
            sim.Tick(.25);
            sim.S.money = -800;
            for (int i = 0; i < ChapterOneSim.DebtSaleDay; i++) sim.Tick(sim.Config.dayLengthSeconds);
            Assert.That(sim.ConfirmComputerSale(), Is.True);
            Assert.That(sim.S.bankrupt, Is.True);
            Assert.That(runtime.SaveNow(), Is.True, runtime.SaveStatus);
            Assert.That(runtime.SaveNow(), Is.True, runtime.SaveStatus); // primary and .bak both hold the ended game
        }

        // ───────────── expected to fail on the baseline ─────────────

        [Test] public void RestartWhoseMarkCannotBeSavedStaysOnTheEndedGameAndSaysSo()
        {
            GoBankrupt();
            var ended = runtime.Sim;
            byte[] primary = Bytes(Primary), backup = Bytes(Backup);
            Action fault = () => throw new InvalidOperationException("injected collector failure");
            runtime.Saving += fault;

            Assert.That(runtime.StartOverAfterBankruptcy(), Is.False, "the choice could not be written: the card stays");
            Assert.That(runtime.Sim, Is.SameAs(ended), "no new game in memory over the ended game on disk");
            Assert.That(runtime.Sim.S.bankrupt, Is.True);
            Assert.That(runtime.Sim.S.restartChosen, Is.False, "the unsaved mark is withdrawn");
            Assert.That(runtime.SaveStatus, Does.Contain("没有重新开始").And.Contain("保存失败"));
            Assert.That(Bytes(Primary), Is.EqualTo(primary), "primary byte-identical");
            Assert.That(Bytes(Backup), Is.EqualTo(backup), ".bak byte-identical");
            Assert.That(Directory.GetFiles(directory, "chapter-one.sav.gameover-*").Length, Is.EqualTo(1), "the timestamped copy is kept, nothing deleted");

            // Quitting now shows the card again on the next start (the disk is the ended game).
            runtime.Saving -= fault;
            Open();
            Assert.That(runtime.Sim.S.bankrupt, Is.True);
            // The player retries once collection works again.
            Assert.That(runtime.StartOverAfterBankruptcy(), Is.True, runtime.SaveStatus);
            Assert.That(runtime.Sim.S.bankrupt, Is.False);
            Open();
            Assert.That(runtime.Sim.S.bankrupt, Is.False);
            Assert.That(runtime.Sim.InPrologue, Is.False);
        }

        [Test] public void RestartWhoseNewGameCannotBeSavedReportsItAndKeepsTheChoiceOnDisk()
        {
            GoBankrupt();
            int calls = 0;
            Action secondFails = () => { if (++calls > 1) throw new InvalidOperationException("injected new-game failure"); };
            runtime.Saving += secondFails;

            Assert.That(runtime.StartOverAfterBankruptcy(), Is.True, "the mark is saved: the restart happened");
            Assert.That(calls, Is.EqualTo(2), "mark save, then the new game's first save");
            Assert.That(runtime.Sim.S.bankrupt, Is.False);
            Assert.That(runtime.Sim.InPrologue, Is.False);
            Assert.That(runtime.SaveStatus, Does.Contain("还没有存进磁盘").And.Contain("保存失败"), "no clean-restart claim");
            Assert.That(Dirty, Is.True, "autosave/quit will retry the new game");
            var disk = DiskState();
            Assert.That(disk.bankrupt && disk.restartChosen, Is.True, "disk holds the ended game with the player's choice");

            runtime.Saving -= secondFails;
            Open();
            Assert.That(runtime.Sim.S.bankrupt, Is.False, "next start honours the choice");
            Assert.That(runtime.Sim.InPrologue, Is.False);
            Assert.That(runtime.Sim.S.aiName, Is.EqualTo("测试"));
            Assert.That(Directory.GetFiles(directory, "chapter-one.sav.gameover-*").Length, Is.EqualTo(1));
        }

        [Test] public void RestartOverAProtectedSaveDoesNotClaimSuccess()
        {
            GoBankrupt();
            File.WriteAllText(Primary, "not a save");
            File.WriteAllText(Backup, "not a backup");
            Assert.That(runtime.ReloadSave(), Is.False, "both generations unreadable: protected");
            Assert.That(runtime.Sim.S.bankrupt, Is.True, "the running ended game is untouched");
            byte[] primary = Bytes(Primary), backup = Bytes(Backup);

            Assert.That(runtime.StartOverAfterBankruptcy(), Is.False);
            Assert.That(runtime.Sim.S.bankrupt, Is.True);
            Assert.That(runtime.SaveStatus, Does.Contain("没有重新开始"));
            Assert.That(Bytes(Primary), Is.EqualTo(primary));
            Assert.That(Bytes(Backup), Is.EqualTo(backup));
        }

        [Test] public void StartupRestartFirstSaveFailureRemainsVisible()
        {
            GoBankrupt();
            runtime.Sim.S.restartChosen = true;
            Assert.That(runtime.SaveNow(), Is.True);
            byte[] primary = Bytes(Primary);

            Open(beforeInitialize: next => next.Saving += () => throw new InvalidOperationException("injected startup failure"));
            Assert.That(runtime.Sim.S.bankrupt, Is.False);
            Assert.That(runtime.Sim.InPrologue, Is.False);
            Assert.That(runtime.SaveStatus, Does.Contain("还没有存进磁盘").And.Contain("injected startup failure"));
            Assert.That(Dirty, Is.True);
            Assert.That(Bytes(Primary), Is.EqualTo(primary));
        }

        [Test] public void ReloadRestartFirstSaveFailureRemainsVisibleInEnglish()
        {
            GoBankrupt();
            runtime.Sim.S.restartChosen = true;
            Assert.That(runtime.SaveNow(), Is.True);
            byte[] primary = Bytes(Primary);
            runtime.Saving += () => throw new InvalidOperationException("injected reload failure");

            using (GameText.Bind(() => GameText.English))
            {
                Assert.That(runtime.ReloadSave(), Is.True, "the saved restart choice is loaded");
                Assert.That(runtime.SaveStatus, Does.Contain("not on disk yet").And.Contain("injected reload failure"));
            }
            Assert.That(runtime.Sim.S.bankrupt, Is.False);
            Assert.That(Dirty, Is.True);
            Assert.That(Bytes(Primary), Is.EqualTo(primary));
        }

        [Test] public void StartupWithOnlyProfileDoesNotHideItsFirstSaveFailure()
        {
            // Only files created inside this fixture's generated directory are removed.
            File.Delete(Primary);
            File.Delete(Backup);
            Open(beforeInitialize: next => next.Saving += () => throw new InvalidOperationException("injected profile startup failure"));

            Assert.That(runtime.Sim.InPrologue, Is.False);
            Assert.That(runtime.SaveStatus, Does.Contain("保存失败").And.Contain("injected profile startup failure"));
            Assert.That(Dirty, Is.True);
            Assert.That(File.Exists(Primary), Is.False);
        }

        [Test] public void TestModeNeverWritesAPlayerProfileEvenAfterADiskStoreWasOpened()
        {
            string fresh = NewTemp();
            Open(fresh); // empty folder: a first-ever start, nothing written yet
            Assert.That(Directory.Exists(fresh), Is.False);
            runtime.SetSimulationForTests(new ChapterOneSim());
            var profile = PrologueProfile.Read("嘴硬心软"); profile.name = "内存"; profile.self = "我"; profile.callMe = "你";
            Assert.That(runtime.CompletePrologue(profile), Is.True, runtime.SaveStatus);
            Assert.That(runtime.SaveNow(), Is.True);
            Assert.That(Directory.Exists(fresh) && Directory.GetFileSystemEntries(fresh).Length > 0, Is.False,
                "TestMode wrote beside a save: " + (Directory.Exists(fresh) ? string.Join(", ", Directory.GetFileSystemEntries(fresh)) : ""));
        }

        // ───────────── regression guards (baseline behaviour) ─────────────

        [Test] public void FailedSaveAfterResetIsReportedAndTheOldProgressIsNotRestoredOnReopen()
        {
            Assert.That(runtime.CaptureChapter(1), Is.True, runtime.SaveStatus);
            runtime.Sim.S.money = 4321;
            Assert.That(runtime.SaveNow(), Is.True);
            Action fault = () => throw new InvalidOperationException("injected reset failure");
            runtime.Saving += fault;

            Assert.That(runtime.ResetProgress(), Is.False, "the new game's save failed and is reported");
            Assert.That(runtime.SaveStatus, Does.Contain("保存失败"));
            Assert.That(File.Exists(Primary), Is.False, "old primary moved aside, not overwritten");
            Assert.That(Directory.GetFiles(directory, "chapter-one.sav.reset-*").Length, Is.GreaterThan(0));

            runtime.Saving -= fault;
            Open();
            Assert.That(runtime.Sim.S.money, Is.Not.EqualTo(4321), "the .reset-* copy is never loaded automatically");
            Assert.That(runtime.Sim.S.bankrupt, Is.False);
            // Documented design, not a restore: chapter snapshots are first-unlock and only load on an explicit choice.
            Assert.That(runtime.ArchiveExists(1, true), Is.True);
        }

        [Test] public void CorruptPrimaryRecoversTheBackupAndKeepsItAsTheGoodGeneration()
        {
            runtime.Sim.S.money = 111; Assert.That(runtime.SaveNow(), Is.True);
            runtime.Sim.S.money = 222; Assert.That(runtime.SaveNow(), Is.True);
            byte[] good = Bytes(Backup);
            File.AppendAllText(Primary, " "); // payload no longer matches its checksum

            Open();
            Assert.That(runtime.Sim.S.money, Is.EqualTo(111));
            Assert.That(runtime.SaveStatus, Does.Contain("备份"));
            // The startup save (offline anchor) rewrote the primary without rotating the corrupt one into .bak.
            Assert.That(Bytes(Backup), Is.EqualTo(good), "the recovered backup is not replaced by the corrupt primary");
            Assert.That(DiskState().money, Is.EqualTo(111));
            Assert.That(runtime.SaveNow(), Is.True, runtime.SaveStatus);
            Assert.That(DiskState().money, Is.EqualTo(111));
        }

        [Test] public void UnreadableSaveIsNeverReplacedByDefaultProgress()
        {
            runtime.Sim.S.money = 5555; Assert.That(runtime.SaveNow(), Is.True);
            File.WriteAllText(Primary, "damaged primary");
            File.WriteAllText(Backup, "damaged backup");
            byte[] primary = Bytes(Primary), backup = Bytes(Backup);

            Open();
            Assert.That(runtime.SaveNow(), Is.False, "write-protected");
            Assert.That(Bytes(Primary), Is.EqualTo(primary));
            Assert.That(Bytes(Backup), Is.EqualTo(backup));
            Assert.That(Directory.GetFiles(directory, "chapter-one.sav*").Length, Is.EqualTo(2), "no extra save generation written");
        }

        [Test] public void LoadingASlotDoesNotCollectTheOutgoingAppsIntoTheIncomingSave()
        {
            runtime.Sim.S.money = 500; Assert.That(runtime.SaveSlot(2), Is.True, runtime.SaveStatus);
            runtime.Sim.S.money = 900; Assert.That(runtime.SaveNow(), Is.True);
            int collected = 0;
            Action stale = () => { collected++; runtime.Sim.S.labState = "stale-from-outgoing-save"; };
            runtime.Saving += stale;
            try
            {
                Assert.That(runtime.LoadArchive(2), Is.True, runtime.SaveStatus);
                Assert.That(collected, Is.Zero, "a load replaces the save; it does not snapshot the outgoing apps into it");
                Assert.That(runtime.Sim.S.money, Is.EqualTo(500));
                var disk = DiskState();
                Assert.That(disk.money, Is.EqualTo(500));
                Assert.That(disk.labState, Is.Not.EqualTo("stale-from-outgoing-save"));
            }
            finally { runtime.Saving -= stale; }
            // App-side identity guards (XingGuang/YY/Tieba linked-Sim checks) own what happens on the next Saving.
        }
    }
}
