        public static int AvailableMemeCount(int today)
        {
            int n = 0; foreach (var p in MemePairs) if (p.since <= today) n += 2; return n;
        }

        public static XgLogicQuestion MemeQuestion(int index, int today, int level)
        {
            var available = new List<int>();
            for (int i = 0; i < MemePairs.Length; i++) if (MemePairs[i].since <= today) available.Add(i);
            if (available.Count == 0) return null;
            index = (index & int.MaxValue) % (available.Count * 2);
            var p = MemePairs[available[index / 2]];
            return new XgLogicQuestion { text = index % 2 == 0 ? p.yes : p.no, textEn = index % 2 == 0 ? p.yes : p.no,
                truth = index % 2 == 0, why = p.why, whyEn = p.why, level = level, category = "网吧逻辑", categoryEn = "Net-cafe logic" };
        }
