            if (OriginalTextSources.TryGetValue(entry.id, out var source)) rights += "\n" + T("原作核验来源：", "Original-text reference: ") + source;
            return rights + "\n" + T("书目资料来源：", "Bibliographic reference: ") + entry.sourceUrl;
